"""Morning Brief: what needs you today, in order.

One deterministic digest built from what is already in the Life Graph —
obligations, promises, today's calendar, and stored alerts. Ranking is
fixed: overdue first, then due today, then due soon, then promises, then
today's events, then alerts. Nothing is generated by an LLM and nothing
is invented: every line names the record it came from. Bilingual
(English/Persian) through the locale parameter.
"""

from __future__ import annotations

from datetime import date

from app.schemas.brief import BriefItem, MorningBrief
from app.services import google_connector as connector
from app.services.life import list_obligations, list_promises
from app.services.notifications import stored_bundle


def _copy(locale: str, en: str, fa: str) -> str:
    return fa if locale == "fa" else en


def today_brief(user_id: str, locale: str = "en", today: date | None = None) -> MorningBrief:
    as_of = today or date.today()
    items: list[BriefItem] = []
    counts = {"overdue": 0, "due_today": 0, "due_soon": 0, "promises": 0, "events_today": 0, "alerts": 0}

    for item in list_obligations(user_id, include_closed=False):
        if item.status.value == "overdue":
            counts["overdue"] += 1
            items.append(
                BriefItem(
                    priority=1,
                    kind="obligation",
                    title=item.title,
                    reason=_copy(locale, "Overdue — act on this first.", "عقب‌افتاده — اول این را انجام دهید."),
                    due_date=item.due_date,
                )
            )
        elif item.due_date == as_of:
            counts["due_today"] += 1
            items.append(
                BriefItem(
                    priority=2,
                    kind="obligation",
                    title=item.title,
                    reason=_copy(locale, "Due today.", "موعد امروز است."),
                    due_date=item.due_date,
                )
            )
        elif item.status.value == "due_soon":
            counts["due_soon"] += 1
            items.append(
                BriefItem(
                    priority=3,
                    kind="obligation",
                    title=item.title,
                    reason=_copy(locale, "Due soon.", "به‌زودی موعدش می‌رسد."),
                    due_date=item.due_date,
                )
            )

    for item in list_promises(user_id, include_closed=False):
        counts["promises"] += 1
        if item.due_date and item.due_date <= as_of:
            items.append(
                BriefItem(
                    priority=2,
                    kind="promise",
                    title=f"{item.counterparty}: {item.promise}",
                    reason=_copy(locale, "A promise is due — check whether it happened.", "قولی موعدش رسیده — بررسی کنید آیا انجام شده است."),
                    due_date=item.due_date,
                )
            )
        elif item.due_date:
            items.append(
                BriefItem(
                    priority=4,
                    kind="promise",
                    title=f"{item.counterparty}: {item.promise}",
                    reason=_copy(locale, "A promise is coming due.", "قولی در راه است."),
                    due_date=item.due_date,
                )
            )

    try:
        events = connector.upcoming_calendar(user_id, 10)
        for event in events:
            if (event.start or "")[:10] == as_of.isoformat():
                counts["events_today"] += 1
                items.append(
                    BriefItem(
                        priority=5,
                        kind="event",
                        title=event.summary,
                        reason=_copy(locale, "On your calendar today.", "امروز در تقویم شما است."),
                        due_date=as_of,
                    )
                )
    except (connector.ConnectorNotConnectedError, connector.ConnectorNotConfiguredError):
        pass

    try:
        bundle = stored_bundle(user_id, locale=locale)
        for alert in bundle.alerts:
            if alert.severity.value in {"urgent", "soon"}:
                counts["alerts"] += 1
                items.append(
                    BriefItem(
                        priority=6,
                        kind="alert",
                        title=alert.title,
                        reason=alert.detail,
                        due_date=None,
                    )
                )
    except Exception:
        pass

    items.sort(key=lambda row: (row.priority, row.due_date or date.max))
    return MorningBrief(date=as_of, locale=locale, items=items, counts=counts)
